// The coastlines on the menu globe.
//
//   node scripts/build-globe-data.mjs
//
// Natural Earth's 110m land outline, thinned to what a 600-pixel globe can
// actually show. The full file is 50 KB of TopoJSON and most of its detail is
// finer than a pixel at that size — a fjord that renders as a third of a pixel
// costs bytes on every page load and shows nothing. What comes out is a plain
// list of rings in degrees, which the component projects itself.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const RAW = 'node_modules/world-atlas/land-110m.json';
const OUT = 'src/ui/globeData.generated.ts';

/**
 * Keep a point only once it is this far from the last one kept, in degrees.
 * Roughly a pixel and a half on a 600-pixel globe.
 */
const MIN_STEP_DEGREES = 0.9;

/** Rings shorter than this are specks: drawn, they are noise. */
const MIN_POINTS = 5;

/** Degrees of latitude/longitude spanned before a ring is worth drawing. */
const MIN_SPAN_DEGREES = 3;

const topology = JSON.parse(readFileSync(RAW, 'utf8'));
const land = feature(topology, topology.objects.land);

/** Every ring in the geometry, whatever nesting it arrived in. */
function ringsOf(geometry) {
  if (geometry.type === 'Polygon') return geometry.coordinates;
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.flat();
  return [];
}

function thin(ring) {
  const kept = [ring[0]];
  for (const point of ring.slice(1)) {
    const [lastLon, lastLat] = kept[kept.length - 1];
    if (Math.hypot(point[0] - lastLon, point[1] - lastLat) >= MIN_STEP_DEGREES) {
      kept.push(point);
    }
  }
  // Close it again: thinning may have dropped the point that met the start.
  if (kept.length > 2) kept.push(kept[0]);
  return kept;
}

function span(ring) {
  const lons = ring.map((p) => p[0]);
  const lats = ring.map((p) => p[1]);
  return Math.max(Math.max(...lons) - Math.min(...lons), Math.max(...lats) - Math.min(...lats));
}

const rings = [];
let rawPoints = 0;
for (const shape of land.features ?? [land]) {
  for (const ring of ringsOf(shape.geometry ?? shape)) {
    rawPoints += ring.length;
    const thinned = thin(ring);
    if (thinned.length < MIN_POINTS) continue;
    if (span(thinned) < MIN_SPAN_DEGREES) continue;
    rings.push(thinned.map(([lon, lat]) => [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]));
  }
}

const points = rings.reduce((n, r) => n + r.length, 0);
const body = rings.map((r) => `  [${r.map(([a, b]) => `[${a},${b}]`).join(',')}],`).join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/build-globe-data.mjs — do not edit.
//
// Land outlines in degrees, [longitude, latitude], thinned for a globe a few
// hundred pixels across. ${rings.length} rings, ${points} points, down from ${rawPoints}.
export const LAND_RINGS: [number, number][][] = [
${body}
];
`,
);

console.log(`rings ${rings.length}, points ${points} (from ${rawPoints})`);
